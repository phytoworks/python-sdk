"""Public operator SDK wire models.

``phytoworks.models`` exports exactly the model types a caller can reach from the public API: the models in
parameter and return annotations of ``PWS``, ``AsyncPWS``, their resources and handles, the exported classes of
``phytoworks`` and ``phytoworks.device``, and the field types and bases of those models, transitively
(``tests/test_public_models.py`` derives the set from the real signatures and fails when this list disagrees).
A name generated from an inline union member, such as ``RuleTriggerConfigCron``, says what the member is (a
singleton tag in the schema or a label pinned in ``scripts/model-allowlist.json``), never its position, so
reordering a union in the Hub schema renames nothing.

``phytoworks.models.generated`` holds every generated class, including ones no public signature mentions. It
is not a supported import path and changes with the Hub schema, so import models from this module.

Every model class is generated from the committed Hub OpenAPI artifact by ``scripts/generate_models.py``; this
module re-exports the supported ones together with the transport's ``Page``/``Pagination`` containers.
"""

